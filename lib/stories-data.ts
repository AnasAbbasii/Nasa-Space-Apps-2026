export const MACHINE_STORIES: Record<string, MachineStory> = {};

// Populate MACHINE_STORIES from MACHINE_DOCUMENTARIES
Object.values(MACHINE_DOCUMENTARIES).forEach(doc => {
  const story: MachineStory = {
    machineId: doc.machineId,
    machineName: doc.machineName,
    body: doc.planet,
    missionTitle: doc.documentaryTitle,
    tagline: doc.tagline,
    slides: doc.slides.map(s => ({
      id: `${doc.machineId}-s${s.slideNumber}`,
      title: s.slideTitle,
      image: s.visualAsset.src,
      caption: s.narrationText,
      duration: s.readingTimeMs,
      audioSrc: s.audioSrc,
      visualNotes: s.visualDirection,
      visualDirection: s.visualDirection,
      onScreenText: s.onScreenText,
      visualAsset: s.visualAsset,
      animation: s.visualAnimation,
    })),
  };
  MACHINE_STORIES[doc.machineId] = story;
  const shortId = doc.machineId.replace(/-lm$/, '');
  MACHINE_STORIES[shortId] = story;
});

export function getDocumentaryForMachine(machineId: string): MachineDocumentary | undefined {
  if (MACHINE_DOCUMENTARIES[machineId]) return MACHINE_DOCUMENTARIES[machineId];
  const normalized = machineId
    .replace(/-lm$/, '')
    .replace(/^pathfinder$/, 'pathfinder-sojourner')
    .replace(/^sojourner$/, 'pathfinder-sojourner')
    .replace(/^spirit$/, 'spirit-mer-a')
    .replace(/^opportunity$/, 'opportunity-mer-b')
    .replace(/^perseverance$/, 'perseverance-ingenuity')
    .replace(/^ingenuity$/, 'perseverance-ingenuity');
  if (MACHINE_DOCUMENTARIES[normalized]) return MACHINE_DOCUMENTARIES[normalized];
  if (MACHINE_DOCUMENTARIES[`${normalized}-lm`]) return MACHINE_DOCUMENTARIES[`${normalized}-lm`];
  return undefined;
}

export function getStoryForMachine(
  machineId: string,
  fallbackMeta?: { name: string; date: string; coordinates: string; purpose: string; body: 'moon' | 'mars' }
): MachineStory {
  if (MACHINE_STORIES[machineId]) return MACHINE_STORIES[machineId];
  const doc = getDocumentaryForMachine(machineId);
  if (doc && MACHINE_STORIES[doc.machineId]) return MACHINE_STORIES[doc.machineId];
  const fallbackKey = fallbackMeta?.body === 'mars' ? 'curiosity' : 'apollo-11-lm';
  return MACHINE_STORIES[fallbackKey] || Object.values(MACHINE_STORIES)[0];
}
